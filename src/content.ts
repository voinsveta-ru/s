/* ---------------------- Подбор ответа чат-бота ---------------------- */

/**
 * Нормализация реплики: нижний регистр, «ё» → «е», пунктуация → пробелы.
 * Приводим и вопрос пользователя, и ключевые слова, поэтому в `CHAT_RULES`
 * достаточно писать основы («цен», «запис») без перечисления форм слова.
 */
export const normalizeChatText = (text: string) =>
  text
    .toLowerCase()
    .replace(/ё/g, "е")
    .replace(/[^a-z0-9а-я\s-]+/gi, " ")
    .replace(/\s+/g, " ")
    .trim();

const WORD_CHAR = /[a-z0-9а-я]/i;

/**
 * Есть ли в тексте основа `key`, начинающаяся с начала слова.
 * Только так: иначе «год» находится внутри «благодарю», а «лет» — внутри
 * «билет», и бот отвечает про возраст вместо «спасибо».
 */
function hasWordStart(haystack: string, key: string): boolean {
  for (let at = haystack.indexOf(key); at !== -1; at = haystack.indexOf(key, at + 1)) {
    if (at === 0 || !WORD_CHAR.test(haystack[at - 1])) return true;
  }
  return false;
}

/**
 * Вес совпадения одного ключевого слова (0 — не совпало).
 * Основа из одного слова ищется с начала слова; фраза из нескольких слов
 * совпадает, если в вопросе нашлись все её слова (пусть и не подряд):
 * так «где вы находитесь?» попадает в правило с ключом «где наход».
 * Вес = длина совпадения: чем конкретнее ключ, тем сильнее правило.
 */
function keywordScore(haystack: string, keyword: string): number {
  const key = normalizeChatText(keyword);
  if (!key) return 0;
  const words = key.split(" ");
  if (words.length > 1) {
    const hit = words.every((word) => word.length > 1 && hasWordStart(haystack, word));
    return hit ? key.length + 3 * (words.length - 1) : 0;
  }
  return hasWordStart(haystack, key) ? key.length : 0;
}

function bestRule(text: string, smallTalk: boolean): ChatRule | null {
  let best: ChatRule | null = null;
  let bestScore = 0;
  for (const rule of CHAT_RULES) {
    if (Boolean(rule.smallTalk) !== smallTalk) continue;
    const score = rule.keywords.reduce(
      (sum, keyword) => sum + keywordScore(text, keyword),
      0,
    );
    /* Строго больше — при равенстве остаётся правило выше по списку */
    if (score > bestScore) {
      bestScore = score;
      best = rule;
    }
  }
  return best;
}

/**
 * Ответ на реплику пользователя. Сначала ищем содержательное правило
 * (и берём самое «весомое» совпадение, а не первое попавшееся), затем —
 * вежливое, и только потом fallback.
 */
export function findChatAnswer(text: string): ChatRule {
  const haystack = normalizeChatText(text);
  if (haystack) {
    return bestRule(haystack, false) ?? bestRule(haystack, true) ?? CHAT_FALLBACK;
  }
  return CHAT_FALLBACK;
}
